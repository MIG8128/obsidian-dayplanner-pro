const DICTIONARIES: Record<Locale, Dictionary> = { en, ko, ja, zh };

let languageSetting: LanguageSetting = 'auto';

/** Called with the plugin's Language setting on load and on every settings save */
export function setLanguage(language: LanguageSetting | undefined) {
    languageSetting = language ?? 'auto';
}

/** Maps an Obsidian / moment language code onto a supported locale ('zh-tw' etc. → 'zh'; unknown → 'en') */
export function normalizeLocale(code: string | null | undefined): Locale {
    const lang = (code ?? '').trim().toLowerCase();
    if (lang.startsWith('ko')) return 'ko';
    if (lang.startsWith('ja')) return 'ja';
    if (lang.startsWith('zh')) return 'zh';
    return 'en';
}

/** Obsidian keeps its UI language in localStorage ('language'; unset means English); moment follows it as a fallback */
function detectObsidianLocale(): Locale {
    let code: string | null = null;
    try {
        code = window.localStorage.getItem('language');
    } catch {
        // Storage can be unavailable (sandboxed / private contexts)
    }
    if (!code) code = (window as any).moment?.locale?.() ?? null;
    return normalizeLocale(code);
}

export function getLocale(): Locale {
    return languageSetting === 'auto' ? detectObsidianLocale() : languageSetting;
}

/** Translated string for `key` in the active locale (English when the locale lacks it); {name} filled from `vars` */
export function t(key: TranslationKey, vars?: Record<string, string | number>): string {
    const text = DICTIONARIES[getLocale()][key] ?? en[key] ?? key;
    if (!vars) return text;
    return text.replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match));
}
